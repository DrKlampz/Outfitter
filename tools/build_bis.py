def item_line(id_):
    f=items.get(id_)
    if not f: return None
    side=f[4] if len(f)>4 else ''
    twin=f[5] if len(f)>5 else ''
    srcs=[]
    for sx in (f[7]+'~').split('~'):
        if not sx: continue
        r=render(sx)
        if r: srcs.append(r)
    # keep up to 3, different kinds first
    out=[];seen=set()
    for r in srcs:
        if len(out)>=3: break
        key=(r[0],r[1])
        if key in seen: continue
        seen.add(key); out.append(r)
    txt='~'.join('%s^%s^%s'%(a,b,c) for a,b,c in out)
    return '%s|%s|%s|%s'%(f[0],side,twin,txt)
